//Billing zip code
$(document).ready(function () {
    $('#billing_zip').on('input', function () {
        let zip = $(this).val();
        zip = zip.replace(/\D/g, ''); 
        if (zip.length > 6) {
            zip = zip.substring(0, 6); 
        }
        $(this).val(zip);
    });
});

